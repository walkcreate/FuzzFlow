/// When lifting encounters a merge node, it directly lifts the phi node's inputs
/// instead of invoking the phi node's lift function
///
/// The phi node's lift function is only called when the phi itself serves as
/// input to other consumers
///
void JavaScriptLifter::visit(shared_ptr<PhiNode> &node)
{
    if (const vector<shared_ptr<VarSymbol>> var_syms = get_varSymbols_on_producer(node);
        !var_syms.empty())
    {
        visit_outcome = var_syms[0]->name;
        return;
    }

    /// Code generation for phi nodes is already handled at `IfNode` and `LoopBegin`.
    /// Here, we only need to return the variable name associated with the phi node.
    const shared_ptr<VarSymbol> var_sym = get_phi_main_proxy(node);
    visit_outcome = var_sym->name;
}

