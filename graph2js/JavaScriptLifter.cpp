void JavaScriptLifter::visit(shared_ptr<FunctionPropertyNode> &node)
{
    const shared_ptr<DataProducerNode> prop_name_node = node->property_name();

    this->in_edge_stack.push(InEdgeType::Data);
    prop_name_node->accept(*this);
    this->in_edge_stack.pop();

    string prop_name = visit_outcome;

    auto method_graph = node->function_graph.lock();

    /*
     * TODO:
     * gecko-dev_js_src_jit-test_tests_warp_store-element-hole-sparse-element.js
     */
    if (method_graph == nullptr) {
        throw LiftError("null function prop graph");
    }

    JavaScriptLifter method_lifter(method_graph);
    method_lifter.lift();

    ScriptWriter script_writer;
    const string literal_code = script_writer.emit_method(method_lifter.function_args, method_lifter.top_region);

    visit_outcome = prop_name + literal_code + ",";
}

