void JavaScriptLifter::build_node2varProxy(const map<shared_ptr<VarProxy>,
                                                     weak_ptr<DataProducerNode>>& varProxy2node)
{
    for (auto& [_proxy, _node] : varProxy2node) {
        if (! this->node2varProxy.contains(_node)) {
            this->node2varProxy.insert({_node, {_proxy}});
        }
        else {
            this->node2varProxy[_node].push_back(_proxy);
        }
    }

    if (! graph->splice_graph_varProxy2node.empty()) {
        for (auto& [_proxy, _node] : graph->splice_graph_varProxy2node) {
            if (! this->node2varProxy.contains(_node)) {
                this->node2varProxy.insert({_node, {_proxy}});
            }
            else {
                this->node2varProxy[_node].push_back(_proxy);
            }
        }
    }
}

vector<shared_ptr<VarSymbol>> JavaScriptLifter::get_varSymbols_on_producer(const weak_ptr<DataProducerNode>& producer)
{
    vector<shared_ptr<VarSymbol>> var_syms;

    if (this->node2varProxy.contains(producer))
    {
        for (const auto& _proxy : this->node2varProxy[producer]) {
            var_syms.push_back(_proxy->var_symbol);
        }
    }

    return var_syms;
}

vector<shared_ptr<VarProxy>> JavaScriptLifter::get_varProxies_on_producer(const weak_ptr<DataProducerNode>& producer)
{
    vector<shared_ptr<VarProxy>> var_proxies;

    if (this->node2varProxy.contains(producer))
    {
        for (const auto& _proxy : this->node2varProxy[producer]) {
            var_proxies.push_back(_proxy);
        }
    }

    return var_proxies;
}

void JavaScriptLifter::update_varSymbol2Regions(vector<shared_ptr<VarSymbol>>& var_syms)
{
    const weak_ptr<Region> region = this->current_region_single;

    for (auto& var_sym : var_syms)
    {
        if (auto regions_pos = this->varSymbol2Regions.find(var_sym);
            regions_pos != this->varSymbol2Regions.end())
        {
            auto& regions = regions_pos->second;
            regions.insert(region);
        }
        else {
            set<weak_ptr<Region>, std::owner_less<>> regions = {region};
            this->varSymbol2Regions.insert({{var_sym, regions}});
        }
    }
}

/// If a `var proxy` is attached to a data producer node, record the corresponding assignment's generated `regionNested`.
/// Note: `regionNested` may not be within the scope of its later uses.
/// If it's not found in the parent chain of `Region` during later processing, the assignment must be regenerated.
///
void JavaScriptLifter::update_region2varProxies(const weak_ptr<DataProducerNode>& node)
{
    vector<shared_ptr<VarProxy>> node_var_proxies = this->get_varProxies_on_producer(node);

    weak_ptr<const RegionNested> region = this->current_region_single->parent_region;

    auto pos = this->region2varProxies.find(region);

    if (pos != this->region2varProxies.end()) {
        auto& proxies = pos->second;

        for (auto& var_proxy : node_var_proxies) {
            proxies.push_back(var_proxy);
        }
    }
    else {
        vector<shared_ptr<VarProxy>> proxies;
        for (auto& var_proxy : node_var_proxies) {
            proxies.push_back(var_proxy);
        }
        this->region2varProxies.insert({{region, proxies}});
    }
}

void JavaScriptLifter::check_region_single()
{
    if (this->current_region_single == nullptr)
    {
        this->current_region_single = make_shared<RegionSingle>();
        this->current_parent_region->add_region(this->current_region_single);
    }
}

/// Check whether a var symbol has been assigned within the accessible scope (current or any outer regions).
bool JavaScriptLifter::varProxy_reach_current_region(const shared_ptr<VarProxy> &var_proxy)
{
    weak_ptr<const RegionNested> region_nested = this->current_region_single->parent_region;

    bool varProxyAlreadyAvailable = false;
    bool has_shadowed_variable = false;

    while (region_nested.lock() != nullptr)
    {
        if (this->region2varProxies.contains(region_nested))
        {
            auto assigned_proxies = this->region2varProxies[region_nested];

            const vector<shared_ptr<VarProxy>> proxies_v (assigned_proxies.begin(),assigned_proxies.end());

            /// Search in reverse order because the later proxy is generated by a subsequent assignment,
            /// making it closer to the current position.
            for (int i = assigned_proxies.size() - 1; i >= 0; i--) {
                if (assigned_proxies[i] == var_proxy) {
                    varProxyAlreadyAvailable = true;
                    break;
                }

                /// If the execution reaches this point, it means the current proxy i is not the target var proxy we are looking for.
                /// However, if their names are the same, it indicates an identifier naming conflict, and proxy i interferes with the
                /// data flow of var proxy. In such a case, the assignment statement for var proxy should be regenerated.
                if (assigned_proxies[i]->var_symbol->name == var_proxy->var_symbol->name)
                {
                    weak_ptr<DataProducerNode> node_1;
                    if (this->graph->varProxy2node.contains(assigned_proxies[i])) {
                        node_1 = this->graph->varProxy2node.at(assigned_proxies[i]);
                    }

                    weak_ptr<DataProducerNode> node_2;
                    if (this->graph->varProxy2node.contains(var_proxy)) {
                        node_2 = this->graph->varProxy2node.at(var_proxy);
                    }

                    if ((! node_1.expired())
                        && (! node_2.expired())
                        && node_1.lock() == node_2.lock())
                    {
                        /// If the two proxies are different but reference the same node,
                        /// this does not correspond to the case where a variable with the same name exists in the reachable scope.
                        continue;
                    }

                    has_shadowed_variable = true;
                    break;
                }
            }
        }

        if (has_shadowed_variable) {
            break;
        }

        region_nested = region_nested.lock()->parent_region.lock();
    }

    return varProxyAlreadyAvailable;
}

/// A data producer node may have multiple attached var proxies.
/// Check whether all corresponding `var` symbols are assigned within the current scope.
///
bool JavaScriptLifter::all_varProxy_available(const weak_ptr<DataProducerNode>& node)
{
    vector<shared_ptr<VarProxy>> var_proxies = this->get_varProxies_on_producer(node);

    /// Check whether all var symbols attached to the node have been assigned within the current scope.
    bool all_assigned = true;

    for (const auto& var_proxy : var_proxies) {

        if (const bool has_assigned = this->varProxy_reach_current_region(var_proxy);
            ! has_assigned)
        {
            all_assigned = false;
            break;
        }
    }

    return all_assigned;
}

void JavaScriptLifter::gen_assignment_for_producer(const weak_ptr<DataProducerNode>& producer,
                                                   const string &assign_expr,
                                                   const  bool self_assignment)
{
    vector<shared_ptr<VarSymbol>> var_syms = this->get_varSymbols_on_producer(producer);

    if (var_syms.empty()) {
        return;
    }

    /// Maintain the mapping between var symbols and regions in preparation for generating declaration statements.
    this->update_varSymbol2Regions(var_syms);

    /// Maintain the mapping between regions and var proxies to determine whether an assignment statement should be
    /// generated when revisiting this data producer.
    this->update_region2varProxies(producer);

    /// This on-demand generation approach may place the assignment in a lower scope level,
    /// which can lead to the variable being out of scope when it's needed later.
    ///
    const shared_ptr<RegionSingle> region = this->current_region_single;
    region->emit_assignment(var_syms, assign_expr, self_assignment);
}

uint32_t JavaScriptLifter::lift()
{
    const shared_ptr<FunctionHeadNode> function_head = dynamic_pointer_cast<FunctionHeadNode>(this->graph->nodes[0]);

    assert_or_throw_graph2js((function_head != nullptr),
        "The first node in graph nodes should be FunctionHeadNode");

    const auto region_single = make_shared<RegionSingle>();
    this->current_region_single = region_single;
    this->current_parent_region->add_region(region_single);

    this->function_name = function_head->get_label();

    for (auto& param_node : function_head->get_params())
    {
        /// Function parameters should not be handled on demand during the lift process,
        /// as this may lead to inconsistent parameter order and argument mismatches when multiple parameters are involved.
        /// Here, function parameters are processed separately by recording their names in `function args`,
        /// so that lifting to a `TerminalNode` only needs to return the parameter name.
        ///
        this->function_args.push_back(param_node.lock()->get_parameter_name());

        /// function args can be seen as declared variables
        vector<shared_ptr<VarSymbol>> var_symbols = this->get_varSymbols_on_producer(param_node);
    }

    /// traverse begin

    this->in_edge_stack.push(InEdgeType::Ctrl);
    function_head->next()->accept(*this);
    this->in_edge_stack.pop();

    /// traverse finished

    /// Generate declarations for variables
    for (auto& [var_sym, regions] : this->varSymbol2Regions) {
        /// For each var symbol, identify all `Region`s where it appears and compute their lowest common ancestor (`RegionNested`).
        /// The first encountered `regionSingle` is chosen as the declaration location.
        auto mini_parent = Region::get_mini_parent_region(regions);

        shared_ptr<RegionSingle> _region = dynamic_pointer_cast<RegionSingle>(mini_parent.lock()->get_first_region());

        assert_or_throw_graph2js((_region != nullptr),
            "The first region in region nested is RegionSingle");

        _region->emit_var_declaration(var_sym);
    }

    return visited_nodes_num;
}

