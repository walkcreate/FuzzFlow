void JavaScriptLifter::visit(const shared_ptr<DataProducerNode> &node)
{
    const vector<shared_ptr<VarSymbol>> attached_vars = this->get_varSymbols_on_producer(node);

    const auto has_visited = visited_nodes.contains(node);

    const bool isVarProxiesFullyAssigned = this->all_varProxy_available(node);

    string producer_expr;

    if (!has_visited || attached_vars.empty() || !isVarProxiesFullyAssigned) {
        /// Cases requiring traversal of both child nodes:
        ///
        /// 1. First visit to this node
        /// 2. Node contains no attached variables (returns expression)
        /// 3. Var proxy on node is unreachable in current scope
        ///     (previous assignment was generated in narrower scope)
        ///
        visited_nodes.insert(node);

        this->in_edge_stack.push(InEdgeType::Data);
        producer_expr = node->get_producer_expr(*this);
        this->in_edge_stack.pop();
    }

    bool self_assignment = false;
    if (const auto binary = dynamic_pointer_cast<BinaryOpNode>(node)) {
        if (OperatorPairs::assignment_op.contains(binary->op->code)) {
            self_assignment = true;
        }
    }

    if ((!attached_vars.empty()) && (!isVarProxiesFullyAssigned)) {
        // When attached var proxies exist but aren't all accessible in current region,
        // we need to generate assignments for them.
        this->gen_assignment_for_producer(node, producer_expr, self_assignment);
    }

    if (!attached_vars.empty()) {
        visit_outcome = attached_vars[0]->name;
    }
    else {
        visit_outcome = producer_expr;
    }
}

